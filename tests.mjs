import assert from 'node:assert/strict';
import { colorPicker } from './utils/colorPicker.js';
import { passwordGenerator } from './utils/passwordGenerator.js';
import { converter } from './utils/converter.js';
import { encoder } from './utils/encoder.js';
import { timestamp } from './utils/timestamp.js';
import { jsonFormatter } from './utils/jsonFormatter.js';
for (const value of ['rgb(255,,0,0)', 'hsl(0 50deg% 50%)', 'rgb(1 2 3 0.5)', 'rgb(1,2,3/0.5)']) assert.throws(() => colorPicker.parse(value));
assert.equal(colorPicker.formats(colorPicker.parse('rgb(255 0 0 / 50%)')).hex, '#FF000080');
assert.equal(colorPicker.formats(colorPicker.parse('hsl(1turn 100% 50%)')).hex, '#FF0000');
for (let i = 0; i < 100; i++) {
  const result = passwordGenerator.generate(16, { uppercase: true, lowercase: true, digits: true, symbols: true, avoidAmbiguous: true, exclude: '{}[]' });
  assert.ok(result.success); assert.equal(result.result.length, 16);
  assert.ok(!/[Il1O0o|{}\[\]]/.test(result.result));
  assert.ok(/[A-Z]/.test(result.result) && /[a-z]/.test(result.result) && /\d/.test(result.result) && /[^A-Za-z0-9]/.test(result.result));
}
assert.equal(passwordGenerator.generate(4, { digits: true, exclude: '0123456789' }).success, false);
assert.equal(converter.convert('9007199254740993', 10, 16).result, '20000000000001');
assert.equal(converter.fromDecimal(65535n, 16, true, true, true).result, '0xFFFF');
assert.equal(converter.fromDecimal(65536n, 16, true, true, true).result, '0x1 0000');
assert.equal(converter.toDecimal('12x', 10).success, false);
assert.equal(encoder.encode('urlFull', 'https://x/a b?q=a&x=1').result, 'https://x/a%20b?q=a&x=1');
assert.equal(encoder.encode('url', '/?=').result, '%2F%3F%3D');
assert.equal(timestamp.dateToTimestamp('2026-02-30 00:00:00', 'UTC').success, false);
assert.equal(timestamp.dateToTimestamp('2026-11-01 01:30:00', 'America/New_York').success, false);
assert.equal(timestamp.dateToTimestamp('2026-03-08 02:30:00', 'America/New_York').success, false);
assert.match(timestamp.timestampToDate('0', 's', 'Asia/Kathmandu').localTime, /UTC\+05:30/);
assert.equal(jsonFormatter.format("{'x': True, 's': 'None'}").parsed.s, 'None');
assert.equal(jsonFormatter.format('{bad').success, false);
assert.match(jsonFormatter.format('{bad').error, /附近/);
assert.equal(jsonFormatter.format(' '.repeat(5 * 1024 * 1024 + 1)).success, false);
assert.equal(jsonFormatter.search({ 'a/b': 1 }, '/a~1b')[0].value, 1);
const kathmandu = timestamp.dateToTimestamp('2026-11-10 12:00:00', 'Asia/Kathmandu');
assert.ok(kathmandu.success);
assert.match(kathmandu.localTime, /12:00:00 \(UTC\+05:45\)/);
assert.match(timestamp.dateToTimestamp('2026-07-01 12:00:00', 'America/New_York').localTime, /UTC-04:00/);
assert.equal(timestamp.timestampToDate('0', 's', 'Not/AZone').success, false);
const invalidJson = jsonFormatter.format('{\n  "x": 1,}');
assert.equal(invalidJson.line, 2);
assert.equal(invalidJson.column, 10);
assert.equal(invalidJson.locationExact, true);
assert.match(invalidJson.error, /第 2 行，第 10 列/);
assert.match(invalidJson.error, /附近/);
const unfinished = jsonFormatter.format('{\n');
assert.equal(unfinished.line, 2);
assert.equal(unfinished.column, 1);
assert.equal(unfinished.locationExact, true);
const originalParse = jsonFormatter.parse;
try {
  jsonFormatter.parse = () => { throw new SyntaxError('Unexpected end of JSON input'); };
  const fallback = jsonFormatter.format('{\n');
  assert.equal(fallback.line, 2); assert.equal(fallback.column, 1);
  assert.equal(fallback.locationExact, false);
  assert.match(fallback.error, /未提供准确位置/);
  jsonFormatter.parse = () => { throw new SyntaxError('invalid JSON at line 2 column 3'); };
  const lineOnly = jsonFormatter.format('{\n  ?');
  assert.equal(lineOnly.line, 2); assert.equal(lineOnly.column, 3);
  assert.equal(lineOnly.locationExact, true);
} finally { jsonFormatter.parse = originalParse; }
assert.equal(jsonFormatter.format(' '.repeat(5 * 1024 * 1024 + 1)).line, undefined);
assert.equal(jsonFormatter.search(Object.fromEntries(Array.from({ length: 150 }, (_, i) => ['match' + i, i])), 'match').length, 100);
const wide = Object.fromEntries(Array.from({ length: 100001 }, (_, i) => ['key' + i, i]));
assert.equal(jsonFormatter.search(wide, 'key100000').length, 0);
assert.match(jsonFormatter.searchText({ user: { name: 'test' } }, '/user/name'), /test/);
assert.match(jsonFormatter.searchText({}, 'missing'), /最多扫描 100000/);
assert.ok(jsonFormatter.preview('x'.repeat(10000)).length <= 1002);
console.log('Algorithm boundary tests passed');
